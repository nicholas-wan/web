// Puts the taller phone versions of the internship scenes into the page.
//   node tools/scenes/phone/apply.cjs
// Each folder here generates one phone-only scene (scene-m.html, scene-m.css):
//   shopee/gen.py, league/gen.cjs, league-ab/league-ab-motion-m.py
// (rerun a folder's generator after changing its desktop scene; shopee and
// league read a saved copy of the desktop svg, orig*.html, so refresh that
// copy first). This script then places each svg right after its desktop svg
// in experience.html and writes the CSS between the phone-scenes markers in
// assets/css/internship-peek.css. Phones (<=736px) see the phone svg; wider
// screens the desktop one; the hidden one never renders or animates.
const fs = require('fs'); const path = require('path');
const root = path.join(__dirname, '..', '..', '..');
const SCENES = [['shopee', 'sp-brand'], ['league', 'league-brand-scene'], ['league-ab', 'lgab-scene']];
let page = fs.readFileSync(path.join(root, 'experience.html'), 'utf8');
let css = '';
// Index just past the </svg> that closes the <svg at `at`.
function close(text, at) {
  const tag = /<svg\b|<\/svg>/g; tag.lastIndex = at; let depth = 0, m;
  while ((m = tag.exec(text))) { depth += m[0] === '</svg>' ? -1 : 1; if (!depth) return m.index + 6; }
  throw new Error('unclosed svg at ' + at);
}
for (const [dir, cls] of SCENES) {
  const svg = fs.readFileSync(path.join(__dirname, dir, 'scene-m.html'), 'utf8').trim().replace(/\s*\n\s*/g, ' ');
  if (!svg.startsWith(`<svg class="${cls} ${cls}--m"`)) throw new Error(`${dir}: scene-m.html must start with <svg class="${cls} ${cls}--m"`);
  // drop any earlier copy, then insert after the desktop svg (scenes nest
  // <svg> elements, so match the closing tag by depth)
  for (let old; (old = page.indexOf(`<svg class="${cls} ${cls}--m"`)) >= 0;) page = page.slice(0, old) + page.slice(close(page, old));
  const at = page.indexOf(`<svg class="${cls}"`);
  if (at < 0) throw new Error(`no desktop svg.${cls} in experience.html`);
  const end = close(page, at);
  page = page.slice(0, end) + svg + page.slice(end);
  css += `\n/* ${dir} */\n` + fs.readFileSync(path.join(__dirname, dir, 'scene-m.css'), 'utf8').replace(/\r\n/g, '\n').trim() + '\n';
}
fs.writeFileSync(path.join(root, 'experience.html'), page);
const file = path.join(root, 'assets', 'css', 'internship-peek.css');
const sheet = fs.readFileSync(file, 'utf8');
const START = '/* phone-scenes:start */', STOP = '/* phone-scenes:end */';
const head = `/* Generated by tools/scenes/phone/apply.cjs: edit the scene folders and rerun. */
.internship-demo-card__plot > svg[class*="--m"] { display: none; }
@media screen and (max-width: 736px) {
${SCENES.map(([, c]) => `  .internship-demo-card__plot > svg.${c}:not(.${c}--m)`).join(',\n')} { display: none; }
  .internship-demo-card__plot > svg[class*="--m"] { display: block; }
}`;
const block = START + '\n' + head + css + STOP;
fs.writeFileSync(file, sheet.includes(START) ? sheet.slice(0, sheet.indexOf(START)) + block + sheet.slice(sheet.indexOf(STOP) + STOP.length) : sheet.trimEnd() + `

/* Phone versions of the internship scenes (25 Oct 2026; owner: "do longer
   phone versions for the other internship ones"): at 736px and below each
   scene swaps to a taller, stacked drawing of the same story (same artwork,
   strings, beats and timings), so its labels read at 10-14px instead of 7-8px.
   See tools/scenes/phone/. */
${block}
`);
console.log('phone scenes applied:', SCENES.map(s => s[0]).join(', '));
