# Builds the desktop Shopee scene with step notes (scene-d.html, scene-d.css)
# from orig-d.html, the desktop svg.sp-brand as it was before notes (copied
# from experience.html; refresh it if the scene's artwork changes).
#
# The phone scene (tools/scenes/phone/shopee) gives each step a caption and a
# two-line plain note. On desktop the three steps sit side by side to the
# right of the listing, so each note needs a column about 88 units wide; the
# original stages are only 70-80 apart. The artwork is therefore drawn at
# scale S (uniformly, nothing redrawn), and the model and the spec list are
# moved right so the three note columns get equal gutters; the two arrows
# after the word column are lengthened to keep the original 5.5-unit gap at
# both ends. The listing, the chips and the word column share one wrapper,
# so the chips still land exactly on their rows.
#
# Usage: python gen.py            (reads orig-d.html)
import os, re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..', '..', '..'))
src = open(os.path.join(HERE, 'orig-d.html'), encoding='utf8').read()  # the desktop svg before notes

i = src.index('<svg class="sp-brand"')
depth = 0
for m in re.finditer(r'<svg\b|</svg>', src[i:]):
    depth += -1 if m.group() == '</svg>' else 1
    if depth == 0:
        svg = src[i:i + m.end()]
        break

S = 0.88            # artwork scale
NOTE = 9.8          # note size in viewBox units (about 11.4px at 1366)
CAP = 12.0          # caption size, local units (the existing .sp-label 12px)
LINE = 1.3 * NOTE   # note line pitch
H = 144             # viewBox height
NOTES = {'words': ('Breaks the title', 'into tokens.'),
         'model': ('One model', 'per language.'),
         'attrs': ('Fills in the', 'product specs.')}
# widest line of each note at 10 units of Merriweather 300 (measured in Chrome)
WIDE = {'words': 70.9, 'model': 63.3, 'attrs': 67.7}
k = NOTE / 10

def f(v): return ('%.2f' % v).rstrip('0').rstrip('.')

# ---- horizontal layout, in viewBox units -----------------------------------
# listing 2..118, word rows 140..197 (centre 168.5), model 219..259 (239),
# spec list 278..358 (318), all local.
RX = 358 - 358 * S                          # spec list keeps its right edge
words_note_r = 168.5 * S + WIDE['words'] * k / 2
attrs_note_l = RX + 318 * S - WIDE['attrs'] * k / 2
model_c = (words_note_r + attrs_note_l) / 2  # equal gutters either side
MX = model_c - 239 * S
GUTTER = (attrs_note_l - words_note_r - WIDE['model'] * k) / 2

# ---- vertical layout, local units -----------------------------------------
CAP_Y = 125.5                              # word rows end at 95, the model tag at 101.5
NOTE_Y = CAP_Y + 1.38 * NOTE / S           # caption to first note line
PITCH = LINE / S

def note(key, n, x):
    return (f'<text class="sp-d-note sp-d-note-{n}" text-anchor="middle">'
            + ''.join(f'<tspan x="{f(x)}" y="{f(NOTE_Y + j * PITCH)}">{t}</tspan>'
                      for j, t in enumerate(NOTES[key])) + '</text>')

def arrow(x0, x1):
    return f'M{f(x0)} 75H{f(x1)}M{f(x1 - 3)} 72L{f(x1)} 75L{f(x1 - 3)} 78'

def sub(old, new, s):
    assert s.count(old) == 1, old
    return s.replace(old, new)

gap = 5.5   # the listing-to-words arrow's gap at each end, local
a1 = ((197 + gap) * S - MX) / S, ((MX + 219 * S) - gap * S - MX) / S
a2 = ((MX + (259 + gap) * S) - RX) / S, (RX + (278 - gap) * S - RX) / S

out = svg
out = sub('viewBox="0 0 360 150"', f'viewBox="0 0 360 {H}"', out)
out = sub('<g class="sp-card">', f'<g class="sp-d-wrap" transform="scale({f(S)})"><g class="sp-card">', out)
out = sub('\n<g class="sp-model">', f'</g>\n<g class="sp-d-wrap" transform="translate({f(MX)} 0) scale({f(S)})"><g class="sp-model">', out)
out = sub('\n<g class="sp-result">', f'</g>\n<g class="sp-d-wrap" transform="translate({f(RX)} 0) scale({f(S)})"><g class="sp-result">', out)
out = sub('\n<filter id="spLift"', '</g>\n<filter id="spLift"', out)
out = sub('d="M202.5 75H213.5M210.5 72L213.5 75L210.5 78"', f'd="{arrow(*a1)}"', out)
out = sub('d="M263 75H274M271 72L274 75L271 78"', f'd="{arrow(*a2)}"', out)
for key, n, x, word in (('words', 1, 168.5, 'Words'), ('model', 2, 239, 'Model'), ('attrs', 3, 318, 'Attributes')):
    old = f'<text class="sp-label" x="{f(x)}" y="129" text-anchor="middle">{word}</text>'
    out = sub(old, f'<text class="sp-label" x="{f(x)}" y="{f(CAP_Y)}" text-anchor="middle">{word}</text>' + note(key, n, x), out)

open(os.path.join(HERE, 'scene-d.html'), 'w', encoding='utf8', newline='\n').write(out + '\n')

# ---- css --------------------------------------------------------------------
D = 'svg.sp-brand:not(.sp-brand--m)'
T = 180 / S - 60                     # listing's opening offset, local px
TY = (H / 2 - 76 * S) / S            # and its drop, so it opens centred
css = f'''/* Shopee, desktop (>736px): the phone's step notes under each step.
   Generated by tools/scenes/desktop/shopee/gen.py. The artwork is drawn at
   {f(S)}x so three two-line notes fit side by side ({f(GUTTER)}-unit gutters); the
   viewBox is 360x{H}. Base styles are the final frame; each note fades in
   just after its step arrives, on the phone's timings. */
.internship-demo-card__plot > {D} {{ aspect-ratio: 360 / {H}; }}
{D} .sp-d-note {{ font-family: "Merriweather", Georgia, serif; font-size: {f(NOTE / S)}px; font-weight: 300; fill: #596273; }}
.is-playing {D} .sp-d-note-1 {{ animation: sp-d-note-in 0.5s 1.95s both; }}
.is-playing {D} .sp-d-note-2 {{ animation: sp-d-note-in 0.5s 4.35s both; }}
.is-playing {D} .sp-d-note-3 {{ animation: sp-d-note-in 0.5s 5.75s both; }}
/* The listing still opens centred in the card, then settles top left. */
{D} .sp-card {{ transform: translate({f(T)}px, {f(TY)}px); }}
.is-still {D} .sp-card {{ transform: none; }}
@keyframes sp-d-note-in {{ from {{ opacity: 0; }} to {{ opacity: 1; }} }}
'''
open(os.path.join(HERE, 'scene-d.css'), 'w', encoding='utf8', newline='\n').write(css)
print(f'S={S} MX={f(MX)} RX={f(RX)} gutter={f(GUTTER)} model_c={f(model_c)} a1={a1} a2={a2} noteY={f(NOTE_Y)}')
