// Puts the desktop internship scenes, with their step captions and notes, into the page.
//   node tools/scenes/desktop/apply.cjs
// Each folder here (shopee, league, league-ab) holds scene-d.html, the whole
// desktop svg (same class, artwork and timings as before, plus the notes the
// phone versions carry; owner, 26 Oct 2026: "desktop charts dont have this
// fidelity of descriptions"), and scene-d.css, the notes' own rules. This
// script swaps each desktop svg in experience.html and writes the CSS between
// the desktop-notes markers in assets/css/internship-peek.css. Rebuild a
// folder's scene-d.* with its gen script first.
const fs = require('fs'); const path = require('path');
const root = path.join(__dirname, '..', '..', '..');
const SCENES = [['shopee', 'sp-brand'], ['league', 'league-brand-scene'], ['league-ab', 'lgab-scene']];
const pageFile = path.join(root, 'experience.html');
let page = fs.readFileSync(pageFile, 'utf8');
let css = '';
// Index just past the </svg> that closes the <svg at `at` (scenes nest svgs).
function close(text, at) {
  const tag = /<svg\b|<\/svg>/g; tag.lastIndex = at; let depth = 0, m;
  while ((m = tag.exec(text))) { depth += m[0] === '</svg>' ? -1 : 1; if (!depth) return m.index + 6; }
  throw new Error('unclosed svg at ' + at);
}
for (const [dir, cls] of SCENES) {
  const html = path.join(__dirname, dir, 'scene-d.html');
  if (!fs.existsSync(html)) { console.log('skip', dir); continue; }
  const svg = fs.readFileSync(html, 'utf8').trim().replace(/\s*\n\s*/g, ' ');
  if (!svg.startsWith(`<svg class="${cls}"`)) throw new Error(`${dir}: scene-d.html must start with <svg class="${cls}"`);
  const at = page.indexOf(`<svg class="${cls}"`);
  if (at < 0) throw new Error(`no desktop svg.${cls} in experience.html`);
  page = page.slice(0, at) + svg + page.slice(close(page, at));
  css += `\n/* ${dir} */\n` + fs.readFileSync(path.join(__dirname, dir, 'scene-d.css'), 'utf8').replace(/\r\n/g, '\n').trim() + '\n';
}
fs.writeFileSync(pageFile, page);
const file = path.join(root, 'assets', 'css', 'internship-peek.css');
const sheet = fs.readFileSync(file, 'utf8');
const START = '/* desktop-notes:start */', STOP = '/* desktop-notes:end */';
const block = `${START}\n/* Generated by tools/scenes/desktop/apply.cjs: edit the scene folders and rerun. */${css}${STOP}`;
fs.writeFileSync(file, sheet.includes(START)
  ? sheet.slice(0, sheet.indexOf(START)) + block + sheet.slice(sheet.indexOf(STOP) + STOP.length)
  : sheet.trimEnd() + `\n\n/* Desktop step notes (26 Oct 2026): the internship scenes' desktop drawings
   carry the same bold step captions and short notes as the phone versions.
   See tools/scenes/desktop/. */\n${block}\n`);
console.log('desktop notes applied');
