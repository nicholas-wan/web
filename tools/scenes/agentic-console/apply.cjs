// Puts the Agentic AI card's "Hunt from a report" peek on Experience (README "Agentic AI console peek").
//   node tools/scenes/agentic-console/build.cjs && node tools/scenes/agentic-console/apply.cjs
// In experience.html, replaces the #agentic-ai card's peek (its hint line and the internship-demo-peek it
// introduces) with peek.cjs's markup around scene.html; it also retires the old scroll story if it finds one.
// In assets/css/internship-peek.css, writes scene.css, peek.css and peek.cjs's generated timing between the
// agentic-console markers. The peek's behaviour (dock, states, Pause/Resume/Replay) is in agentic-peek.js, which
// internship-peek.js loads from the peek's data-script on its first open.
const fs = require('fs'); const path = require('path');
const peek = require('./peek.cjs');
const root = path.join(__dirname, '..', '..', '..');
const scene = fs.readFileSync(path.join(__dirname, 'scene.html'), 'utf8').trim().replace(/\s*\n\s*/g, ' ');
const sceneCss = fs.readFileSync(path.join(__dirname, 'scene.css'), 'utf8').replace(/\r\n/g, '\n').trim();
const peekCss = fs.readFileSync(path.join(__dirname, 'peek.css'), 'utf8').replace(/\r\n/g, '\n').trim();

// the element that starts at index i, through its matching close tag
function end(html, i) {
  const tag = html.slice(i).match(/^<(\w+)/)[1];
  const re = new RegExp(`<(/?)${tag}\\b[^>]*>`, 'g'); re.lastIndex = i;
  let depth = 0, m;
  while ((m = re.exec(html))) { depth += m[1] ? -1 : 1; if (!depth) return re.lastIndex; }
  throw new Error('unclosed ' + tag);
}
const pageFile = path.join(root, 'experience.html');
let page = fs.readFileSync(pageFile, 'utf8');
const card = page.indexOf('id="agentic-ai"'), stop = page.indexOf('</article>', card);
if (card < 0 || stop < 0) throw new Error('no #agentic-ai card in experience.html');
let from = page.indexOf('<p class="internship-demo-hint">', card), to;
if (from > -1 && from < stop) {
  const wrap = page.indexOf('<div class="internship-demo-peek" data-company="agentic"', from);
  if (wrap < 0 || wrap > stop) throw new Error('the agentic hint has no peek after it');
  to = end(page, wrap);
} else {
  // the retired scroll story and its inline loader
  from = page.indexOf('<div class="hs-story"', card);
  if (from < 0 || from > stop) throw new Error('no agentic peek (or story) to replace in the #agentic-ai card');
  to = end(page, from);
  const loader = page.slice(to).match(/^<script>\/\* Loads the Agentic AI story[\s\S]*?<\/script>/);
  if (loader) to += loader[0].length;
}
page = page.slice(0, from) + peek.html(scene, sceneCss) + page.slice(to);
fs.writeFileSync(pageFile, page);

const file = path.join(root, 'assets', 'css', 'internship-peek.css');
const sheet = fs.readFileSync(file, 'utf8');
const START = '/* agentic-console:start */', STOP = '/* agentic-console:end */';
if (!sheet.includes(START)) throw new Error('no agentic-console markers in internship-peek.css');
const css = `${sceneCss}\n${peekCss}\n${peek.css(scene, sceneCss)}`;
const block = `${START}\n/* Generated by tools/scenes/agentic-console (build.cjs, then apply.cjs): edit there and rerun. */\n${css}\n${STOP}`;
fs.writeFileSync(file, sheet.slice(0, sheet.indexOf(START)) + block + sheet.slice(sheet.indexOf(STOP) + STOP.length));
console.log('agentic peek applied:', page.length, 'bytes of page,', css.length, 'bytes of CSS');
